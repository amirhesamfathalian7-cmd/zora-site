/** Convert latin digits to Persian digits */
export function toFa(input: string | number): string {
  const map = ["۰", "۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹"];
  return String(input).replace(/[0-9]/g, (d) => map[Number(d)]);
}

/**
 * Download URL for a release file.
 * - Dev / standalone server: relative `/api/download/...` (streams from download/).
 * - Cloudflare Pages build (NEXT_PUBLIC_DL_BASE set): absolute R2 public URL.
 */
export function fileUrl(filename: string): string {
  const base = process.env.NEXT_PUBLIC_DL_BASE;
  return base ? `${base.replace(/\/+$/, "")}/${filename}` : `/api/download/${filename}`;
}

/** Format bytes-ish MB numbers like «۹۱۵ مگابایت» */
export function fmtMB(mb: number): string {
  return `${toFa(Math.round(mb))} مگابایت`;
}

